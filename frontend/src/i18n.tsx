type I18nContextValue = {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: string, params?: Record<string, string | number>) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

function getStoredLanguage(): Language {
  return 'ja'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(() => getStoredLanguage())

  useEffect(() => {
    document.documentElement.lang = language

    const title = isCompanySite ? translations[language].companyMetaTitle : translations[language].metaTitle
    const description = isCompanySite
      ? translations[language].companyMetaDescription
      : translations[language].metaDescription
    const keywords = isCompanySite ? translations[language].companyMetaKeywords : translations[language].metaKeywords

    if (typeof title === 'string') {
      document.title = title
    }

    if (typeof description === 'string') {
      const descriptionTag = document.querySelector('meta[name="description"]')
      if (descriptionTag) descriptionTag.setAttribute('content', description)
    }

    if (typeof keywords === 'string') {
      const keywordsTag = document.querySelector('meta[name="keywords"]')
      if (keywordsTag) keywordsTag.setAttribute('content', keywords)
    }
  }, [language])

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      setLanguage,
      t: (key, params = {}) => {
        const entry = translations[language][key]
        if (typeof entry === 'function') return entry(params)
        return entry ?? key
      },
    }),
    [language],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const context = useContext(I18nContext)
  if (!context) {
    throw new Error('useI18n must be used within I18nProvider')
  }

  return context
}
